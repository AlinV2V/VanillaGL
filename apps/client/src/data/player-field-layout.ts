export const PLAYER_FIELD_LAYOUT_SHIFT = 6;
export const PLAYER_FIELD_SHIFT_ANCHOR = 0x0b6;
// The reversed Build 5875 client descriptors use the stock values below. The vMaNGOS enum formulas
// include OBJECT_END in UNIT_END and therefore serialize this player block six fields later; live
// equipment/quest captures independently confirm that +6 wire layout.
export function playerField(stockIndex: number): number {
  return stockIndex >= PLAYER_FIELD_SHIFT_ANCHOR ? stockIndex + PLAYER_FIELD_LAYOUT_SHIFT : stockIndex;
}
